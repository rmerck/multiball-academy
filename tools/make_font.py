FIRST, LAST = 32, 95  # Space to underscore: upper case, digits, punctuation.


def rows(ch):
    glyph = GLYPHS.get(ch, GLYPHS["?"])
    assert len(glyph) == 7 and all(len(r) == 5 and set(r) <= {"#", "."} for r in glyph), ch
    return [sum(1 << (4 - i) for i, c in enumerate(r) if c == "#") for r in glyph]


def main():
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/make_font.py. Do not edit by hand.",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace pinball::font {",
        "",
        "inline constexpr int kGlyphWidth = 5;",
        "inline constexpr int kGlyphHeight = 7;",
        "// Horizontal advance per character, in font pixels.",
        "inline constexpr int kAdvance = 6;",
        "inline constexpr char kFirstChar = %d;" % FIRST,
        "inline constexpr char kLastChar = %d;" % LAST,
        "",
        "// One byte per row, top to bottom. Bit 4 is the leftmost pixel.",
        "inline constexpr std::array<std::array<std::uint8_t, 7>, %d> kGlyphs{{" % (LAST - FIRST + 1),
    ]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        values = ", ".join("0x%02X" % v for v in rows(ch))
        shown = ch if ch not in "\\" else "backslash"
        note = "" if ch in GLYPHS else " (not drawn: shows ?)"
        lines.append("    {{%s}},  // %s%s" % (values, repr(shown), note))
    lines += ["}};", "", "}  // namespace pinball::font", ""]
    out = Path(__file__).resolve().parent.parent / "src" / "platform" / "Font5x7.hpp"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
