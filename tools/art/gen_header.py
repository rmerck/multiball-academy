# Writes src/generated/ArtPalette.hpp: the colours and constants the renderer's code-drawn elements share
# with the art (lamp colours, tints, backdrop colour, glow limits, ball sprite size). One source: palette.py.
#   python3 gen_header.py [out_file]          write the header (default: src/generated/ArtPalette.hpp)
#   python3 gen_header.py --check <file>      exit 1 unless <file> is what palette.py gives (ctest art_palette)
# Needs nothing but Python itself, so the check runs wherever the tests do.
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # palette.py beside this file, also under python3 -I

import palette as P  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
DEFAULT = os.path.join(ROOT, "src", "generated", "ArtPalette.hpp")


def rgb(h):
    return "{%d, %d, %d}" % P.rgb(h)


def text():
    lines = ["// Generated by tools/art/gen_header.py from tools/art/palette.py. Do not edit.", "#pragma once", "",
             "#include <array>", "#include <cstdint>", "", "namespace pinball::art {", "",
             "struct Rgb { std::uint8_t r, g, b; };", ""]
    for name in ("INK", "NIGHT", "DECK_A", "DECK_B", "WELL", "WELL_HI", "VIOLET", "ORCHID", "TEAL", "AQUA", "PINK", "ORANGE",
                 "YELLOW", "GREEN", "BLUE", "CREAM", "CH_HI", "CH_MID", "CH_LO"):
        lines.append("inline constexpr Rgb k%s%s;" % ("".join(w.capitalize() for w in name.split("_")), rgb(getattr(P, name))))
    lines += ["", "// Letterbox and backdrop colour (screen::kBackdropRgb, LaunchBackground.colorset).",
              "inline constexpr Rgb kBackdrop%s;" % rgb(P.NIGHT), "",
              "// Lamp colours in LampId order: tint for the insert sprite and for its glow.",
              "inline constexpr std::array<Rgb, %d> kLampColours{{" % len(P.LAMPS)]
    for name, col in P.LAMPS:
        lines.append("    %s,  // %s" % (rgb(col), name))
    lines += ["}};", "", "// Colour multiplier for each lamp when lit (light hues are held down so the ball stays the lightest thing).",
              "inline constexpr std::array<float, %d> kLampLitLevels{{" % len(P.LAMPS)]
    lines.append("    " + ", ".join("%.2fF" % P.lit_level(col) for _, col in P.LAMPS))
    lines += ["}};", "", "// Where each of the seven shot arrows points, in LampId order (playfield units).",
              "inline constexpr std::array<std::array<float, 2>, %d> kArrowAims{{" % len(P.LAMP_AIM)]
    for name, _ in P.LAMPS[:len(P.LAMP_AIM)]:
        lines.append("    {%.1fF, %.1fF},  // %s" % (P.LAMP_AIM[name][0], P.LAMP_AIM[name][1], name))
    lines += ["}};", "inline constexpr float kInsertArrowUnits = %.1fF;" % P.INSERT_ARROW_UNITS,
              "inline constexpr float kInsertArrowBriefingScale = %.1fF;" % P.INSERT_ARROW_BRIEFING,
              "inline constexpr float kInsertRoundPerDiameter = %.4fF;" % P.INSERT_ROUND_PER_DIAMETER, ""]
    for key, col in P.TINT.items():
        lines.append("inline constexpr Rgb kTint%s%s;" % ("".join(w.capitalize() for w in key.split("_")), rgb(col)))
    lines += ["", "// Visibility rule (docs/ASSETS.md): the ball is the lightest thing on the table.",
              "inline constexpr float kUnlitInsertLevel = %.2fF;   // colour multiplier for an unlit insert" % P.UNLIT_LEVEL,
              "inline constexpr float kMaxGlowStrength = %.2fF;    // strongest additive glow on the playfield" % P.GLOW_STRENGTH_MAX,
              "inline constexpr float kLampGlowStrength = %.2fF;" % P.GLOW_STRENGTH_LAMP,
              "inline constexpr float kArrowGlowRadiusPerSize = %.2fF;" % P.GLOW_RADIUS_ARROW,
              "inline constexpr float kRoundGlowRadiusPerDiameter = %.2fF;" % P.GLOW_RADIUS_ROUND,
              "inline constexpr float kBallSpriteUnits = %.1fF;    // ball.png covers this; the disc is two ball radii" % P.BALL_SPRITE_UNITS,
              "inline constexpr float kBallShadowOffsetX = %.1fF;" % P.BALL_SHADOW_OFFSET[0],
              "inline constexpr float kBallShadowOffsetY = %.1fF;" % P.BALL_SHADOW_OFFSET[1],
              "inline constexpr float kBallShadowAlpha = %.2fF;" % P.BALL_SHADOW_ALPHA, "", "}  // namespace pinball::art", ""]
    return "\n".join(lines)


def main(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text())


def check(path):
    with open(path, newline="") as f:
        if f.read() != text():
            sys.exit("%s is not what tools/art/palette.py gives: run python3 tools/art/gen_header.py" % path)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        check(sys.argv[2])
    elif len(sys.argv) <= 2:
        main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    else:
        sys.exit("usage: gen_header.py [out_file] | --check <file>")
