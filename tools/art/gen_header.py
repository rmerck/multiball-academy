# Writes src/generated/ArtPalette.hpp: the colours and constants the renderer's code-drawn elements share
# with the art (lamp colours, tints, backdrop colour, glow limits, ball sprite size). One source: palette.py.
#   python3 gen_header.py [out_file]          write the header (default: src/generated/ArtPalette.hpp)
#   python3 gen_header.py --check <file> [<colorset>]   exit 1 unless <file> is what palette.py gives and
#                                             the colour set (the iOS launch screen's) is the backdrop colour
#                                             (ctest art_palette)
# Needs nothing but Python itself, so the check runs wherever the tests do.
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # palette.py beside this file, also under python3 -I

import palette as P  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
DEFAULT = os.path.join(ROOT, "src", "generated", "ArtPalette.hpp")


def rgb(h):
    return "{%d, %d, %d}" % P.rgb(h)


def all_lamps():
    """Every LampId's name and colour, in LampId order: the rev 2 lamps, then revision 3's planned inserts."""
    return list(P.LAMPS) + [(name, col) for name, col, _, _ in P.PLANNED_LAMPS]


def text():
    lines = ["// Generated by tools/art/gen_header.py from tools/art/palette.py. Do not edit.", "#pragma once", "",
             "#include <array>", "#include <cstdint>", "#include <string_view>", "", "namespace pinball::art {", "",
             "struct Rgb { std::uint8_t r, g, b; };", ""]
    for name in ("INK", "NIGHT", "DECK_A", "DECK_B", "WELL", "WELL_HI", "VIOLET", "ORCHID", "TEAL", "AQUA", "PINK", "ORANGE",
                 "YELLOW", "GREEN", "BLUE", "CREAM", "CH_HI", "CH_MID", "CH_LO"):
        lines.append("inline constexpr Rgb k%s%s;" % ("".join(w.capitalize() for w in name.split("_")), rgb(getattr(P, name))))
    lines += ["", "// Letterbox and backdrop colour (screen::kBackdropRgb, LaunchBackground.colorset).",
              "inline constexpr Rgb kBackdrop%s;" % rgb(P.NIGHT), "",
              "// Lamp colours in LampId order: tint for the insert sprite and for its glow.",
              "inline constexpr std::array<Rgb, %d> kLampColours{{" % len(all_lamps())]
    for name, col in all_lamps():
        lines.append("    %s,  // %s" % (rgb(col), name))
    lines += ["}};", "", "// Colour multiplier for each lamp when lit (light hues are held down so the ball stays the lightest thing).",
              "inline constexpr std::array<float, %d> kLampLitLevels{{" % len(all_lamps())]
    lines.append("    " + ", ".join("%.2fF" % P.lit_level(col) for _, col in all_lamps()))
    lines += ["}};", "", "// Where each of the seven shot arrows points, in LampId order (playfield units).",
              "inline constexpr std::array<std::array<float, 2>, %d> kArrowAims{{" % len(P.LAMP_AIM)]
    for name, _ in P.LAMPS[:len(P.LAMP_AIM)]:
        lines.append("    {%.1fF, %.1fF},  // %s" % (P.LAMP_AIM[name][0], P.LAMP_AIM[name][1], name))
    lines += ["}};", "inline constexpr float kInsertArrowUnits = %.1fF;" % P.INSERT_ARROW_UNITS,
              "inline constexpr float kInsertArrowBriefingScale = %.1fF;" % P.INSERT_ARROW_BRIEFING,
              "inline constexpr float kInsertRoundPerDiameter = %.4fF;" % P.INSERT_ROUND_PER_DIAMETER, ""]
    for key, col in P.TINT.items():
        lines.append("inline constexpr Rgb kTint%s%s;" % ("".join(w.capitalize() for w in key.split("_")), rgb(col)))
    lines += ["", "// Visibility rule (docs/ASSETS.md): the ball is the lightest thing on the table.",
              "inline constexpr float kUnlitInsertLevel = %.2fF;   // colour multiplier for an unlit insert" % P.UNLIT_LEVEL,
              "inline constexpr float kMaxGlowStrength = %.2fF;    // strongest additive glow on the playfield" % P.GLOW_STRENGTH_MAX,
              "inline constexpr float kLampGlowStrength = %.2fF;" % P.GLOW_STRENGTH_LAMP,
              "inline constexpr float kArrowGlowRadiusPerSize = %.2fF;" % P.GLOW_RADIUS_ARROW,
              "inline constexpr float kRoundGlowRadiusPerDiameter = %.2fF;" % P.GLOW_RADIUS_ROUND,
              "inline constexpr float kBallSpriteUnits = %.1fF;    // ball.png covers this; the disc is two ball radii" % P.BALL_SPRITE_UNITS,
              "inline constexpr float kBallShadowOffsetX = %.1fF;" % P.BALL_SHADOW_OFFSET[0],
              "inline constexpr float kBallShadowOffsetY = %.1fF;" % P.BALL_SHADOW_OFFSET[1],
              "inline constexpr float kBallShadowAlpha = %.2fF;" % P.BALL_SHADOW_ALPHA,
              "inline constexpr float kBallShadowRadii = %.1fF;    // the contact shadow, in ball radii" % P.BALL_SHADOW_RADII, ""]
    lines += ["// Light show: lit lamps in the neon of their colour, LampId order, with the lens level for each.",
              "inline constexpr std::array<Rgb, %d> kLampNeon{{" % len(all_lamps())]
    for name, col in all_lamps():
        lines.append("    %s,  // %s" % (rgb(P.NEON[col]), name))
    lines += ["}};", "inline constexpr std::array<float, %d> kLampNeonLevels{{" % len(all_lamps()),
              "    " + ", ".join("%.2fF" % P.neon_level(P.NEON[col]) for _, col in all_lamps()), "}};", ""]
    for key, col in P.FX.items():
        lines.append("inline constexpr Rgb kFx%s%s;" % ("".join(w.capitalize() for w in key.split("_")), rgb(col)))
    lines += ["inline constexpr float kNeonGlowStrength = %.2fF;" % P.GLOW_STRENGTH_NEON,
              "inline constexpr float kFlasherStrengthMax = %.2fF;" % P.FLASHER_STRENGTH_MAX,
              "inline constexpr float kGiStrength = %.2fF;" % P.GI_STRENGTH,
              "inline constexpr float kGiStrengthTop = %.2fF;  // at the Altitude's top level" % P.GI_STRENGTH_TOP,
              "inline constexpr int kGiBulbs = %d;" % P.GI_BULBS,
              "inline constexpr float kGiBulbStrength = %.2fF;" % P.GI_BULB_STRENGTH,
              "inline constexpr float kGiBulbStrengthTop = %.2fF;" % P.GI_BULB_STRENGTH_TOP,
              "// The GI bulbs' colour at each Altitude level, FL100 to FL500.",
              "inline constexpr std::array<Rgb, %d> kAltitudeGi{{" % len(P.ALTITUDE_GI),
              *["    %s," % rgb(c) for c in P.ALTITUDE_GI], "}};",
              "inline constexpr float kBallPoolAlpha = %.2fF;  // the dark pool round each ball" % P.BALL_POOL_ALPHA,
              "inline constexpr float kBallPoolRadii = %.1fF;  // its radius in ball radii" % P.BALL_POOL_RADII,
              "inline constexpr float kFlareUnits = %.1fF;    // flare.png and ring.png at scale 1" % P.FLARE_UNITS,
              ""]
    lines += ["// Revision 3 (TABLE_REV3.md 3.10): the inserts baked into the background for the LampIds from",
              "// DroneArmour1 on (in this order, after the rev 2 lamps in kLampColours and the rest), and the flasher",
              "// domes (FlasherId). Positions are the art's (tools/art/palette.py); TableLayout.hpp uses exactly these.",
              "enum class InsertShape : std::uint8_t { Round, Hex, Chevron };",
              "struct PlannedLamp {", "  std::string_view name;", "  InsertShape shape;", "  float x, y;",
              "  Rgb colour, neon;", "  float litLevel, neonLevel;", "};",
              "inline constexpr float kLadderDiameter = %.1fF;" % P.LADDER_DIAMETER,
              "inline constexpr float kHexDiameter = %.1fF;" % P.HEX_DIAMETER,
              "inline constexpr float kChevronWidth = %.1fF;" % P.CHEVRON_SIZE[0],
              "inline constexpr float kChevronHeight = %.1fF;" % P.CHEVRON_SIZE[1],
              "inline constexpr std::array<PlannedLamp, %d> kPlannedLamps{{" % len(P.PLANNED_LAMPS)]
    shapes = {"round": "Round", "hex": "Hex", "chevron": "Chevron"}
    for name, col, shape, (x, y) in P.PLANNED_LAMPS:
        lines.append('    {"%s", InsertShape::%s, %.1fF, %.1fF, %s, %s, %.2fF, %.2fF},' % (
            name, shapes[shape], x, y, rgb(col), rgb(P.NEON[col]), P.lit_level(col), P.neon_level(P.NEON[col])))
    lines += ["}};", "struct FlasherDome {", "  std::string_view name;", "  float x, y;", "  Rgb colour, neon;", "};",
              "inline constexpr float kFlasherDomeUnits = %.1fF;" % P.FLASHER_DOME_UNITS,
              "inline constexpr std::array<FlasherDome, %d> kFlasherDomes{{" % len(P.FLASHER_DOMES)]
    for name, col, (x, y) in P.FLASHER_DOMES:
        lines.append('    {"%s", %.1fF, %.1fF, %s, %s},' % (name, x, y, rgb(col), rgb(P.NEON[col])))
    lines += ["}};",
              "inline constexpr float kDroneSpriteUnits = %.1fF;    // drone.png, drone_dive.png, drone_down.png" % P.DRONE_SPRITE_UNITS,
              "inline constexpr float kCaptiveBallSpriteUnits = %.1fF;" % P.CAPTIVE_BALL_SPRITE_UNITS,
              "inline constexpr float kStandupSpriteWidth = %.1fF;  // standup_*.png, upright" % P.STANDUP_SPRITE_UNITS[0],
              "inline constexpr float kStandupSpriteHeight = %.1fF;" % P.STANDUP_SPRITE_UNITS[1],
              ""]
    lines += table_a()
    lines += ["}  // namespace pinball::art", ""]
    return "\n".join(lines)


TABLE_A_OUT = os.path.join(HERE, "table_a", "out")
# The sheets tools/art/table_a/ship.py puts in assets/table_a (two pixels per unit), as the renderer draws them.
TABLE_A_SHIPPED = ["drone", "propwash", "propwash_blur", "pylon", "bay_door", "flight_deck", "ramp_runway",
                   "ramp_skyway", "jet_caps", "flasher_domes", "inserts_arrows", "inserts_flaps", "inserts_altitude",
                   "altitude_plate"]
TABLE_A_GROUPS = ["Layout", "Ladder", "Altitude", "Flaps", "Bogey", "Radar", "SafetyPost", "Multiball", "DeckLit",
                  "Approach"]


def camel(label):
    return "k" + "".join(w[:1].upper() + w[1:].lower() for w in label.replace(" ", "_").split("_"))


def table_a():
    """Table A (concept A): the shipped sheets' layout and the whole insert plan, from tools/art/table_a/out."""
    import json
    import math
    sheets = {}
    for name in ("sheets.json", "gimp_sheets.json"):
        with open(os.path.join(TABLE_A_OUT, name)) as f:
            sheets.update(json.load(f)["sheets"])
    with open(os.path.join(TABLE_A_OUT, "lamp_plan.json")) as f:
        plan = json.load(f)["lamps"]
    lines = ["// ---- Table A (concept A, Flight Academy): tools/art/table_a, shipped in assets/table_a ----",
             "// Colours of the masters (palette.py TABLE_A).",
             *["inline constexpr Rgb kA%s%s;" % ("".join(w.capitalize() for w in k.split("_")), rgb(v))
               for k, v in P.TABLE_A.items()],
             "inline constexpr float kAUnlitFloor = %.2fF;" % P.TABLE_A_UNLIT_FLOOR,
             "inline constexpr float kADeckFloodOff = %.2fF;" % P.TABLE_A_DECK_FLOOD[0],
             "inline constexpr float kADeckFloodOn = %.2fF;" % P.TABLE_A_DECK_FLOOD[1],
             "inline constexpr float kAApproach = %.2fF;" % P.TABLE_A_APPROACH,
             "inline constexpr float kAReticle = %.2fF;" % P.TABLE_A_RETICLE,
             "inline constexpr float kABallThrough = %.2fF;" % P.TABLE_A_BALL_THROUGH,
             "inline constexpr float kAGiStrength = %.2fF;" % P.TABLE_A_GI_STRENGTH[0],
             "inline constexpr float kAGiStrengthTop = %.2fF;" % P.TABLE_A_GI_STRENGTH[1],
             "inline constexpr float kAAltitudePlateX = %.1fF;  // its top-left corner" % P.TABLE_A_ALT_PLATE[0],
             "inline constexpr float kAAltitudePlateY = %.1fF;" % P.TABLE_A_ALT_PLATE[1],
             "// A sprite sheet: cells left to right, top to bottom, in frame order; a cell is cellW x cellH units",
             "// (two pixels each); centred on its toy, or its top-left corner at (x, y).",
             "struct Sheet {", "  std::string_view file;", "  float cellW, cellH;", "  int columns, frames;",
             "  bool centred;", "  float x, y;", "};", "namespace sheet {"]
    for name in TABLE_A_SHIPPED:
        sh = sheets[name]
        centred = sh["anchor"] == "centre"
        x, y = (0.0, 0.0) if centred else sh["anchor"]
        lines.append('inline constexpr Sheet k%s{"table_a/%s", %.1fF, %.1fF, %d, %d, %s, %.1fF, %.1fF};' % (
            "".join(w.capitalize() for w in name.split("_")), sh["file"], sh["cellUnits"][0], sh["cellUnits"][1],
            sh["columns"], len(sh["frames"]), "true" if centred else "false", x, y))
    lines.append("}  // namespace sheet")
    radii = sheets["jet_caps"]["radii"]
    lines.append("// The bumper radius each jet cap cell was rendered for (sheets.json).")
    lines.append("inline constexpr std::array<float, %d> kAJetCapRadii{%s};" % (
        len(radii), ", ".join("%.1fF" % r for r in radii)))
    for name in TABLE_A_SHIPPED:
        lines.append("namespace %s {" % name)
        lines.append("  " + " ".join("inline constexpr int %s = %d;" % (camel(f), i)
                                     for i, f in enumerate(sheets[name]["frames"])))
        lines.append("}  // namespace %s" % name)
    shapes = {"arrow": "Arrow", "arrow_mission": "ArrowMission", "pip": "Pip", "rung": "Rung", "flaps": "Flaps",
              "round": "Round", "hex": "Hex", "chevron": "Chevron"}
    lines += ["// Every insert of Table A (tools/art/table_a/out/lamp_plan.json): the unlit lens is baked into",
              "// table_a/background.png; the game draws it lit. group Layout: lamp is a LampId; the others are lit",
              "// by the renderer from the game's state (index: the ladder's arrow * 3 + step, the Altitude level, the",
              "// F-L-A-P-S letter, the approach light's row).",
              "enum class AShape : std::uint8_t { %s };" % ", ".join(shapes[k] for k in shapes),
              "enum class AGroup : std::uint8_t { %s };" % ", ".join(TABLE_A_GROUPS),
              "struct AInsert {", "  AShape shape;", "  AGroup group;", "  int index;", "  float x, y, size, angle;",
              "  Rgb neon;", "  float neonLevel;", "};",
              "inline constexpr std::array<AInsert, %d> kAInserts{{" % len(plan)]
    arrows = [e["name"] for e in plan if e["shape"] in ("arrow", "arrow_mission")]
    for e in plan:
        name, shape = e["name"], e["shape"]
        x, y = e["c"]
        angle = 0.0
        if shape.startswith("arrow"):
            ax, ay = e["aim"]
            angle = math.degrees(math.atan2(ay - y, ax - x)) + 90.0
        if e["source"] == "layout":
            group, index = "Layout", e["id"]
        elif name.startswith("Ladder"):
            group, index = "Ladder", arrows.index(name[:-1].replace("Ladder", "Arrow")) * 3 + int(name[-1]) - 1
        elif name.startswith("Altitude"):
            group, index = "Altitude", int(name[-3]) - 1
        elif name.startswith("Flaps"):
            group, index = "Flaps", "FLAPS".index(name[-1])
        elif name.startswith("Approach"):
            group, index = "Approach", int(name[len("Approach"):-2]) - 1
        else:
            group = next(g for g in TABLE_A_GROUPS if name.startswith(g))
            index = int(name[-1]) - 1 if name[-1].isdigit() else 0
        size = {"arrow": 28.0, "arrow_mission": 34.0}.get(shape, e.get("d", 12.0))
        neon = P.NEON.get(e["colour"], e["colour"])
        lines.append("    {AShape::%s, AGroup::%s, %d, %.1fF, %.1fF, %.1fF, %.2fF, %s, %.2fF},  // %s" % (
            shapes[shape], group, index, x, y, size, angle, rgb(neon), P.neon_level(neon), name))
    lines += ["}};", ""]
    return lines


def main(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text())


def check(path, colorset=None):
    with open(path, newline="") as f:
        if f.read() != text():
            sys.exit("%s is not what tools/art/palette.py gives: run python3 tools/art/gen_header.py" % path)
    if colorset is not None:
        import json
        with open(colorset) as f:
            comp = json.load(f)["colors"][0]["color"]["components"]
        got = tuple(int(comp[k], 16) for k in ("red", "green", "blue"))
        if got != P.rgb(P.NIGHT) or float(comp["alpha"]) != 1.0:
            sys.exit("%s is %s, not the backdrop colour %s" % (colorset, got, P.rgb(P.NIGHT)))


if __name__ == "__main__":
    if len(sys.argv) in (3, 4) and sys.argv[1] == "--check":
        check(*sys.argv[2:])
    elif len(sys.argv) <= 2:
        main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    else:
        sys.exit("usage: gen_header.py [out_file] | --check <file>")
